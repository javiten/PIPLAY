def translate(message, language):
    if language != 'en':
        return message
    if message.startswith('No se pudo cambiar la TFT: '):
        return ENGLISH['No se pudo cambiar la TFT: '] + message.removeprefix('No se pudo cambiar la TFT: ')
    return ENGLISH.get(message, message)


def render(template, language):
    return re.sub(r'\{\{([^{}]+)\}\}', lambda match: translate(match[1], language),
                  template).replace('__LANGUAGE__', language)
